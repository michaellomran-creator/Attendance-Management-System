"use client";

import React, { useCallback, useEffect, useState } from "react";
import {
  AlertCircle,
  CheckCircle2,
  Clock,
  KeyRound,
  LogIn,
  LogOut,
  MonitorSmartphone,
  Settings2,
} from "lucide-react";
import { ApiError, apiFetch } from "@/lib/api";

interface TerminalInfo {
  terminal_id: string;
  terminal_name: string;
  organization_id: string;
  organization_name: string;
  organization_timezone: string;
  location_name: string | null;
  reset_delay_seconds: number;
  server_time_utc: string;
}

interface PunchResult {
  action: string;
  employee_name: string;
  employee_code: string;
  recorded_at_utc: string;
  status: string;
  message: string;
  gross_minutes: number;
  break_minutes: number;
  net_minutes: number;
}

export default function AttendanceTerminalPage() {
  const [terminalToken, setTerminalToken] = useState<string>("");
  const [tokenInput, setTokenInput] = useState<string>("");
  const [terminalInfo, setTerminalInfo] = useState<TerminalInfo | null>(null);
  const [setupError, setSetupError] = useState<string | null>(null);

  const [employeeCode, setEmployeeCode] = useState("");
  const [pin, setPin] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [result, setResult] = useState<PunchResult | null>(null);
  const [punchError, setPunchError] = useState<string | null>(null);
  const [now, setNow] = useState<Date | null>(null);

  // Live clock tick
  useEffect(() => {
    setNow(new Date());
    const timer = setInterval(() => setNow(new Date()), 1000);
    return () => clearInterval(timer);
  }, []);

  const loadTerminalInfo = useCallback(async (token: string) => {
    setSetupError(null);
    try {
      const info = await apiFetch<TerminalInfo>("/terminals/kiosk/info", {
        terminalToken: token,
      });
      localStorage.setItem("noram_terminal_token", token);
      setTerminalToken(token);
      setTerminalInfo(info);
    } catch (err) {
      setTerminalInfo(null);
      setSetupError(
        err instanceof ApiError
          ? err.message
          : "Unable to connect terminal. Verify the terminal token."
      );
    }
  }, []);

  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    const urlToken = params.get("token");
    const saved = urlToken || localStorage.getItem("noram_terminal_token") || "";
    if (saved) {
      setTokenInput(saved);
      loadTerminalInfo(saved);
    }
  }, [loadTerminalInfo]);

  const clearInputs = useCallback(() => {
    setEmployeeCode("");
    setPin("");
  }, []);

  const handlePunch = async (action: "check-in" | "check-out") => {
    if (!terminalToken || !employeeCode.trim() || !pin.trim()) {
      setPunchError("Please enter both Employee ID and PIN.");
      return;
    }
    setSubmitting(true);
    setPunchError(null);
    setResult(null);
    try {
      const res = await apiFetch<PunchResult>(`/terminals/kiosk/${action}`, {
        method: "POST",
        terminalToken,
        body: JSON.stringify({
          employee_code: employeeCode.trim(),
          pin: pin.trim(),
        }),
      });
      setResult(res);
      clearInputs();
      const delay = (terminalInfo?.reset_delay_seconds || 4) * 1000;
      setTimeout(() => {
        setResult(null);
      }, delay);
    } catch (err) {
      clearInputs();
      setPunchError(
        err instanceof ApiError
          ? err.message
          : "Network unavailable. Attendance event was NOT recorded."
      );
    } finally {
      setSubmitting(false);
    }
  };

  if (!terminalInfo) {
    return (
      <div className="min-h-screen bg-[#0F3D3E] flex items-center justify-center p-6">
        <div className="w-full max-w-md bg-white rounded-lg border border-[#D5CDBD] p-8">
          <div className="flex items-center gap-3 mb-4">
            <div className="w-10 h-10 rounded-md bg-[#0F3D3E] text-[#FFD400] flex items-center justify-center">
              <MonitorSmartphone className="w-5 h-5" />
            </div>
            <div>
              <h1 className="text-lg font-semibold text-[#0F3D3E]">
                Register Attendance Terminal
              </h1>
              <p className="text-xs text-[#546A6B]">
                Enter the terminal token generated by your organization administrator.
              </p>
            </div>
          </div>

          {setupError && (
            <div className="mb-4 p-3 rounded bg-red-50 border border-red-200 text-xs text-red-800">
              {setupError}
            </div>
          )}

          <form
            onSubmit={(e) => {
              e.preventDefault();
              loadTerminalInfo(tokenInput.trim());
            }}
            className="space-y-4"
          >
            <div>
              <label className="block text-xs font-medium text-[#0F3D3E] mb-1">
                Terminal Authentication Token
              </label>
              <input
                type="password"
                required
                value={tokenInput}
                onChange={(e) => setTokenInput(e.target.value)}
                placeholder="ntk_..."
                className="w-full px-3 py-2.5 text-sm rounded-md border border-[#D5CDBD] bg-[#FAF9F6] focus:outline-none focus:border-[#0F3D3E]"
              />
            </div>
            <button
              type="submit"
              className="w-full py-2.5 rounded-md bg-[#FFD400] text-[#0F3D3E] font-semibold text-sm hover:bg-[#E6BF00]"
            >
              Connect Terminal
            </button>
          </form>
        </div>
      </div>
    );
  }

  const tz = terminalInfo.organization_timezone || "Africa/Addis_Ababa";
  const formattedTime = now
    ? now.toLocaleTimeString("en-US", {
        timeZone: tz,
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
      })
    : "--:--:--";
  const formattedDate = now
    ? now.toLocaleDateString("en-US", {
        timeZone: tz,
        weekday: "long",
        year: "numeric",
        month: "long",
        day: "numeric",
      })
    : "Loading date...";

  return (
    <div className="min-h-screen bg-[#0F3D3E] flex flex-col justify-between p-4 sm:p-8">
      {/* Top Organization Header */}
      <header className="max-w-2xl w-full mx-auto flex items-center justify-between text-white">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded bg-[#FFD400] text-[#0F3D3E] font-bold flex items-center justify-center text-lg">
            {terminalInfo.organization_name.charAt(0).toUpperCase()}
          </div>
          <div>
            <div className="font-semibold text-base">{terminalInfo.organization_name}</div>
            <div className="text-xs text-[#B8D0D0]">
              {terminalInfo.terminal_name}
              {terminalInfo.location_name ? ` • ${terminalInfo.location_name}` : ""}
            </div>
          </div>
        </div>
        <button
          onClick={() => {
            localStorage.removeItem("noram_terminal_token");
            setTerminalInfo(null);
            setTerminalToken("");
          }}
          title="Disconnect terminal"
          className="p-2 rounded text-[#B8D0D0] hover:text-white hover:bg-[#165254]"
        >
          <Settings2 className="w-5 h-5" />
        </button>
      </header>

      {/* Main Kiosk Card — Sand Putty */}
      <main className="max-w-xl w-full mx-auto my-8 bg-[#F4F1EA] rounded-xl border border-[#D5CDBD] p-6 sm:p-10 shadow-lg">
        {/* Live Clock */}
        <div className="text-center pb-6 mb-6 border-b border-[#D5CDBD]">
          <div className="inline-flex items-center gap-2 text-xs font-medium text-[#0F3D3E] mb-1">
            <Clock className="w-4 h-4" />
            <span>{formattedDate}</span>
          </div>
          <div className="text-4xl sm:text-5xl font-bold tracking-tight text-[#0F3D3E] tabular-nums">
            {formattedTime}
          </div>
        </div>

        {/* Success Feedback */}
        {result && (
          <div className="mb-6 p-4 rounded-lg bg-emerald-50 border border-emerald-300 text-emerald-950 flex items-start gap-3">
            <CheckCircle2 className="w-6 h-6 text-emerald-700 shrink-0 mt-0.5" />
            <div>
              <div className="font-semibold text-base">{result.message}</div>
              <div className="text-xs mt-1 space-y-0.5">
                <div>
                  Action: <strong className="uppercase">{result.action.replace("_", " ")}</strong> • Status:{" "}
                  <strong className="uppercase">{result.status.replace("_", " ")}</strong>
                </div>
                <div>
                  Recorded:{" "}
                  {new Date(result.recorded_at_utc).toLocaleTimeString("en-US", {
                    timeZone: tz,
                  })}
                </div>
                {result.action === "check_out" && (
                  <div>
                    Net Working Time: {Math.floor(result.net_minutes / 60)}h{" "}
                    {result.net_minutes % 60}m
                  </div>
                )}
              </div>
            </div>
          </div>
        )}

        {/* Error Feedback */}
        {punchError && (
          <div className="mb-6 p-4 rounded-lg bg-red-50 border border-red-300 text-red-900 flex items-start gap-3">
            <AlertCircle className="w-5 h-5 text-red-700 shrink-0 mt-0.5" />
            <div className="text-sm font-medium">{punchError}</div>
          </div>
        )}

        {/* Inputs */}
        <div className="space-y-4">
          <div>
            <label className="block text-sm font-semibold text-[#0F3D3E] mb-1.5">
              Employee ID
            </label>
            <input
              type="text"
              autoComplete="off"
              value={employeeCode}
              onChange={(e) => setEmployeeCode(e.target.value)}
              placeholder="e.g. HTL-001"
              className="w-full px-4 py-3 text-lg rounded-md border border-[#C9C0B1] bg-white text-[#0F3D3E] font-medium focus:outline-none focus:border-[#0F3D3E]"
            />
          </div>

          <div>
            <label className="block text-sm font-semibold text-[#0F3D3E] mb-1.5">
              Attendance PIN
            </label>
            <div className="relative">
              <KeyRound className="w-5 h-5 text-[#546A6B] absolute left-3.5 top-1/2 -translate-y-1/2" />
              <input
                type="password"
                inputMode="numeric"
                autoComplete="off"
                value={pin}
                onChange={(e) => setPin(e.target.value)}
                placeholder="••••"
                className="w-full pl-11 pr-4 py-3 text-lg rounded-md border border-[#C9C0B1] bg-white text-[#0F3D3E] tracking-widest focus:outline-none focus:border-[#0F3D3E]"
              />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-4 pt-2">
            <button
              type="button"
              disabled={submitting}
              onClick={() => handlePunch("check-in")}
              className="flex items-center justify-center gap-2 py-4 px-4 rounded-md bg-[#FFD400] text-[#0F3D3E] font-bold text-base hover:bg-[#E6BF00] disabled:opacity-60 transition-colors"
            >
              <LogIn className="w-5 h-5" />
              <span>Check In</span>
            </button>

            <button
              type="button"
              disabled={submitting}
              onClick={() => handlePunch("check-out")}
              className="flex items-center justify-center gap-2 py-4 px-4 rounded-md bg-[#0F3D3E] text-white font-bold text-base hover:bg-[#165254] disabled:opacity-60 transition-colors"
            >
              <LogOut className="w-5 h-5 text-[#FFD400]" />
              <span>Check Out</span>
            </button>
          </div>
        </div>
      </main>

      <footer className="text-center text-xs text-[#B8D0D0]">
        NORAM DIGITAL SOLUTIONS • Authoritative Server Time ({tz})
      </footer>
    </div>
  );
}
